export function canonicalIngredient(name: string) {
  let n = name.split(/[(（,/]/)[0];
  n = n.replace(/[A-Za-z]+/g, "").replace(/\s+/g, "");
  n = n.replace(/^(다진|손질한|손질|데친|삶은|볶은|말린|냉동|슬라이스|채썬|깐)(?=.{2,})/, "");
  return SYNONYMS[n] ?? n;
}
export const isWater = (canonical: string) => /^(물|정수|생수|찬물|뜨거운물)$/.test(canonical);
